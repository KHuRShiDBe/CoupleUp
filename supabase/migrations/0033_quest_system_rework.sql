-- CoupleUp migration 0033: quest bonus milestones become per-person.
--
-- The content/reward-scale side of this rework (120 quest items, 4 periods x
-- 15 items x 2 genders, new per-tier point values 5/10/15 daily,
-- 20/40/60 weekly, 50/100/150 monthly, 200/400/600 yearly) is pure client
-- content (src/constants/questPools/*.ts, questEconomy.ts) -- nothing to
-- migrate for that part, it's just what complete_quest_item is already
-- called with.
--
-- What DOES need a migration: quest_bonus_claims (migration 0021) has always
-- been scoped by (couple_id, period, period_key, milestone) only -- with no
-- user dimension, the "5/7/10 done -> bonus" milestones were effectively
-- shared by the whole couple's combined progress, and only one partner could
-- ever claim a given milestone per day/week. The user explicitly asked for
-- separate per-person tracking, so:
--
--   - quest_bonus_claims gets a user_id column.
--   - claim_quest_bonus now counts only the CALLER's own completed items
--     (completed_by = auth.uid()) instead of the whole couple's, and stamps
--     the claim with the caller's user_id.
--   - The old couple-level unique constraint is dropped and replaced with a
--     per-user partial unique index -- old rows (user_id is null, from
--     before this migration) are exempt from it and untouched, so no
--     existing claim history is lost or altered.
--   - claim_quest_bonus also now rejects monthly/yearly (milestones only
--     ever apply to daily/weekly, per spec) -- server-enforced, not just a
--     client-side tab gate.
--
-- Does NOT touch: quest_progress, quest_custom_items, complete_quest_item,
-- couple_offers/couple_offer_counters, any existing row, public.actions
-- history, BOND rate, roulette costs/coupons, or any other roulette.
--
-- Safe to re-run: ADD COLUMN IF NOT EXISTS, CREATE OR REPLACE FUNCTION,
-- guarded constraint drop -- no data is ever deleted.

-- ============================================================================
-- 1. quest_bonus_claims -- add the per-user dimension.
-- ============================================================================

alter table public.quest_bonus_claims add column if not exists user_id uuid references public.profiles(id) on delete set null;

-- Drop whatever the old couple-level unique constraint is actually named
-- (auto-generated by Postgres from the original inline `unique (...)` in
-- migration 0021) -- found dynamically so this doesn't depend on guessing
-- the exact generated name.
do $$
declare
  v_conname text;
begin
  select conname into v_conname
  from pg_constraint
  where conrelid = 'public.quest_bonus_claims'::regclass
    and contype = 'u';
  if v_conname is not null then
    execute format('alter table public.quest_bonus_claims drop constraint %I', v_conname);
  end if;
end $$;

-- New per-user uniqueness: each user can claim a given milestone at most
-- once per (period, period_key). Partial (user_id is not null) so the old,
-- pre-migration rows (which have no user_id) are never affected by it.
create unique index if not exists quest_bonus_claims_user_period_milestone_key
  on public.quest_bonus_claims (user_id, period, period_key, milestone)
  where user_id is not null;

-- ============================================================================
-- 2. claim_quest_bonus -- re-counts the CALLER's OWN completed quest_progress
--    rows (never the whole couple's) before paying, and only for daily/
--    weekly periods. Same signature as migration 0021 -- CREATE OR REPLACE
--    is enough, no drop needed.
-- ============================================================================

create or replace function public.claim_quest_bonus(
  p_couple_id uuid,
  p_period text,
  p_period_key text,
  p_milestone int,
  p_bonus_points int,
  p_title text
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  actual_count int;
begin
  if not public.is_couple_member(p_couple_id) then
    raise exception 'NOT_A_MEMBER';
  end if;
  if p_period not in ('daily', 'weekly') then
    raise exception 'MILESTONES_NOT_AVAILABLE';
  end if;

  select count(*) into actual_count
  from public.quest_progress
  where couple_id = p_couple_id
    and period = p_period
    and period_key = p_period_key
    and completed_by = auth.uid();

  if actual_count < p_milestone then
    raise exception 'MILESTONE_NOT_REACHED';
  end if;

  insert into public.quest_bonus_claims (couple_id, user_id, period, period_key, milestone, points)
  values (p_couple_id, auth.uid(), p_period, p_period_key, p_milestone, p_bonus_points);

  insert into public.actions (couple_id, author_id, recipient_id, title, points, type)
  values (p_couple_id, auth.uid(), auth.uid(), p_title, p_bonus_points, 'action');

  return true;
exception when unique_violation then
  return false;
end;
$$;

notify pgrst, 'reload schema';
